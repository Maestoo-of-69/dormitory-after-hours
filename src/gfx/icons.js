const cache = {};

export function icon(id) {
  if (!cache[id]) {
    const { c, ctx } = makeCanvas(16, 16);
    (DRAW[id] || DRAW.note)(ctx);
    cache[id] = { canvas: c, url: c.toDataURL() };
  }
  return cache[id];
}
