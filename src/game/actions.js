const by = (g, vlad, angelina) => (g.who === 'vlad' ? vlad : angelina);
const cycle = (g, key, list) => list[(g.inc(key) - 1) % list.length];
const once = (g, key) => {
  if (g.flags[key]) return false;
  g.flags[key] = true;
  return true;
};
// A remark from whoever is NOT active, so idle banter happens between the two.
